"""
Module: Report Generator
=========================
Responsibilities:
- Build complete downloadable analysis reports in plain text / markdown.
- Structure:
    1. Dataset Overview
    2. Data Quality & Cleaning Summary (Before vs After)
    3. Statistical Summary
    4. Key Insights
"""

import io
import pandas as pd
from typing import Dict, Any, List
from modules.insights import generate_factual_insights
from modules.statistics import get_all_numerical_summary
from modules.cleaning import compare_before_after


def generate_text_report(
    file_name: str,
    original_df: pd.DataFrame,
    current_df: pd.DataFrame,
    cleaning_logs: List[str]
) -> str:
    """
    Generate a formatted comprehensive text report of the entire analysis.
    """
    lines = []
    separator = "=" * 70
    sub_sep = "-" * 70

    lines.append(separator)
    lines.append("FILE DATA ANALYSIS SYSTEM - COMPREHENSIVE REPORT")
    lines.append("College Mini-Project in Data Analysis and Essentials")
    lines.append(separator)
    lines.append("")

    # Section 1: Dataset Information
    lines.append("1. DATASET INFORMATION")
    lines.append(sub_sep)
    lines.append(f"Source File Name:       {file_name}")
    lines.append(f"Total Rows (Current):   {len(current_df)}")
    lines.append(f"Total Columns:          {len(current_df.columns)}")
    lines.append(f"Column Names:           {', '.join(current_df.columns)}")
    lines.append("")

    # Section 2: Data Quality & Cleaning Summary
    lines.append("2. DATA QUALITY & CLEANING SUMMARY")
    lines.append(sub_sep)
    if original_df is not None:
        comp_df = compare_before_after(original_df, current_df)
        lines.append(comp_df.to_string(index=False))
        lines.append("")

    lines.append("Cleaning Operations Applied:")
    if cleaning_logs:
        for i, log in enumerate(cleaning_logs, 1):
            lines.append(f"  {i}. {log}")
    else:
        lines.append("  (No cleaning operations applied yet; original data in use)")
    lines.append("")

    # Section 3: Statistical Summary
    lines.append("3. STATISTICAL SUMMARY (NUMERICAL VARIABLES)")
    lines.append(sub_sep)
    stats_df, err = get_all_numerical_summary(current_df)
    if stats_df is not None:
        lines.append(stats_df.to_string(index=False))
    else:
        lines.append(f"  Note: {err}")
    lines.append("")

    # Section 4: Key Insights
    lines.append("4. KEY FACTUAL INSIGHTS")
    lines.append(sub_sep)
    insights = generate_factual_insights(current_df, original_df)
    for ins in insights:
        lines.append(f"* [{ins['category']}] {ins['headline']}")
        lines.append(f"  Detail: {ins['detail']}")
        lines.append("")

    lines.append(separator)
    lines.append("End of Analysis Report - Generated by File Data Analysis System")
    lines.append(separator)

    return "\n".join(lines)


def get_csv_download_bytes(df: pd.DataFrame) -> bytes:
    """Convert DataFrame to CSV bytes for download."""
    if df is None:
        return b""
    return df.to_csv(index=False).encode('utf-8')
